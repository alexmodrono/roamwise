import Ajv, { _ } from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { readFile, writeFile } from 'node:fs/promises';
import { formats } from '../packages/core/formats.js';
const schema = JSON.parse(await readFile(new URL('../packages/core/trip.schema.json', import.meta.url), 'utf8'));
// Workers disallow runtime new Function(). Compile once and ship ordinary JS to both targets.
const ajv = new Ajv({ allErrors: true, useDefaults: true, strict: false, code: { source: true, esm: true, formats: _`formats` } });
for (const [name, validate] of Object.entries(formats)) ajv.addFormat(name, validate);
const validate = ajv.compile(schema);
const code = standaloneCode(ajv, validate).replaceAll('require("ajv/dist/runtime/ucs2length").default', 'codePointLength');
if (code.includes('require(')) throw new Error('Unexpected runtime dependency in standalone validator');
await writeFile(new URL('../packages/core/trip-validator.generated.js', import.meta.url), `// Generated by scripts/compile-trip-schema.mjs. Do not edit.\nimport { formats } from './formats.js';\nconst codePointLength = value => [...value].length;\n${code}\n`);
